// Rewrites src/disposable-domains.ts from the disposable-email-domains
// project's blocklist (https://github.com/disposable-email-domains/disposable-email-domains,
// CC0 1.0, public domain). Run it with `pnpm disposable-domains` and commit the
// result; overrides belong in ALLOWED_DOMAINS in src/signup-protection.ts.
import { writeFileSync } from "node:fs";
import path from "node:path";

const REPO = "disposable-email-domains/disposable-email-domains";
const commit = (
  (await (
    await fetch(`https://api.github.com/repos/${REPO}/commits/main`)
  ).json()) as { sha: string }
).sha;
const list = await fetch(
  `https://raw.githubusercontent.com/${REPO}/${commit}/disposable_email_blocklist.conf`,
);
if (!list.ok) throw new Error(`The blocklist answered ${list.status}`);
const domains = [
  ...new Set(
    (await list.text())
      .split("\n")
      .map((line) => line.trim().toLowerCase())
      .filter((line) => /^[a-z0-9.-]+$/.test(line)),
  ),
].sort();
if (domains.length < 1000)
  throw new Error(
    `Only ${domains.length} domains; refusing to shrink the list`,
  );

const out = path.join(import.meta.dirname, "../src/disposable-domains.ts");
writeFileSync(
  out,
  `// Generated by scripts/disposable-domains.ts. Do not edit.
// Source: https://github.com/${REPO} at ${commit},
// CC0 1.0 (public domain). ${domains.length} domains.
export const DISPOSABLE_DOMAINS = \`
${domains.join("\n")}
\`;
`,
);
console.log(`Wrote ${domains.length} domains from ${commit} to ${out}`);
